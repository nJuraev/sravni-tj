// Package extract отвечает за этап 2 пайплайна: Markdown → строго
// типизированный JSON по контракту ai-output-schema.md через AI в режиме
// structured output (specs/parser.md §3 этап 2, §4).
//
// Интерфейс AIExtractor позволяет мокать AI в тестах и менять провайдера
// (Gemini ↔ Qwen) без изменения оркестратора. Контракт схемы при смене
// провайдера НЕ меняется.
package extract

import (
	"context"
	"fmt"
	"net/http"

	"sravni/parser/internal/config"
	"sravni/parser/internal/model"
)

// Extraction — результат извлечения: типизированные продукты + сырой ответ
// модели (для записи в parser_runs.ai_raw_response, секреты не включаются).
type Extraction struct {
	Result model.ExtractionResult
	// RawResponse — сырой текст ответа модели ДО парсинга (для отладки галлюцинаций).
	RawResponse string
	// Usage — токены запроса (не все провайдеры отдают; nil, если недоступно).
	Usage *TokenUsage
}

// TokenUsage — токены одного AI-вызова, как их отдаёт провайдер (OpenAI-совместимый
// объект usage). Нужен для оценки стоимости прогона (specs — см. обсуждение токенов).
type TokenUsage struct {
	PromptTokens     int
	CompletionTokens int
	TotalTokens      int
}

// AIExtractor — абстракция «Markdown → структурированные продукты».
type AIExtractor interface {
	// Extract вызывает AI в structured-output режиме и возвращает типизированный
	// результат. category — категория задачи, передаётся в промпт как подсказка.
	// sourceURL — URL страницы (или элемента в array-split режиме), помогает
	// AI отличить целевой продукт от чужих предложений на той же странице.
	Extract(ctx context.Context, sourceURL, markdown string, category model.Category) (*Extraction, error)
}

// New возвращает реализацию AIExtractor по конфигу.
func New(cfg *config.Config, client *http.Client) (AIExtractor, error) {
	switch cfg.AIProvider {
	case config.AIGemini:
		return NewGemini(cfg.AIAPIKey, cfg.AIModel, client), nil
	case config.AIQwen:
		return NewQwen(cfg.AIAPIKey, cfg.AIModel, client), nil
	case config.AIOpenRouter:
		return NewOpenRouter(cfg.AIAPIKey, cfg.AIModel, cfg.MaxTokens, client), nil
	case config.AIDeepSeek:
		return NewDeepSeek(cfg.AIAPIKey, cfg.AIModel, cfg.MaxTokens, client), nil
	default:
		return nil, fmt.Errorf("extract: неизвестный AI-провайдер %q", cfg.AIProvider)
	}
}

// PromptVersion — версия контракта экстракции (systemPrompt + responseSchema +
// то, как они собираются в запрос, напр. schemaPromptText для DeepSeek).
// Мешается в skip-if-unchanged хэш (parser/cache.go): если страница банка не
// изменилась, но МЫ поменяли промпт/схему — старый хэш обязан перестать
// совпадать, чтобы продукт заново прошёл через новую логику, а не тихо
// остался с данными, извлечёнными старой версией. Бампать на любое смысловое
// изменение systemPrompt/responseSchema/schemaPromptText — просто +1, номер
// не привязан к семверу проекта.
const PromptVersion = "7"

// commonExtractionRules — правила извлечения ОДНОГО продукта, общие для
// обычного экстрактора (systemPrompt, допускает catalog-режим) и лёгкого
// StaticSourceExtractor (staticSourceSystemPrompt, catalog-режима не
// существует вообще — см. staticsource.go). Вынесено в константу, чтобы два
// промпта не расходились по мере правок.
const commonExtractionRules = `- URL страницы (дан отдельной строкой перед Markdown) может указывать на slug/название конкретного продукта (напр. .../kredit-dastras). Если на странице кроме продукта, которому соответствует URL/заголовок h1, встречаются ДРУГИЕ явно отдельные предложения (иных партнёров/названий, не упомянутые как варианты одного продукта) — извлекай ТОЛЬКО продукт по URL/h1, остальное игнорируй. Это правило не отменяет случай, когда страница намеренно показывает НЕСКОЛЬКО разных продуктов банка (см. подсказку про конкретную страницу, если она есть) — тогда извлекай все, как указано в подсказке.
- Не выдумывай данные. Если значения нет на странице — используй null (где схема это допускает).
- Срок ВСЕГДА в месяцах (год = 12). «До востребования» → term_min = null.
- Ставки — проценты годовых, число в [0..100]. Сумма — в валюте currency (не минор-единицы).
- Если минимальная сумма (amount_min) не указана на странице — верни null (НЕ 0).
- Если продукт предлагается в нескольких валютах с разными ставками — верни ОТДЕЛЬНЫЙ объект на каждую валюту.
- rate_tiers — ОБЯЗАТЕЛЬНО извлекай тарифную сетку целиком, включая случаи, когда разбивка ставки по сроку и/или сумме дана НЕ таблицей, а обычным текстом/буллетом в описании или условиях (напр. «Ставка от 180 до 365 дней: 12% годовых», «от 366 до 731 дней: 15% годовых», «до 50 000 сомони — 10%, свыше — 13%») — каждую такую фразу разложи в отдельный элемент rate_tiers, а НЕ оставляй текстом в key_conditions. Если сетка в тексте задана в ДНЯХ — переведи в месяцы (месяц = 30 дней, округление до целого), сохраняя смежность соседних диапазонов: если после округления верхняя граница одного диапазона совпала с нижней границей следующего, сдвинь нижнюю границу следующего на +1 месяц (напр. 180-365 дней и 366-731 дней → term 6-12 и 13-24, не 6-12 и 12-24). amount_from/amount_to — null, если сумма не участвует в разбивке. Если ставка единая — один элемент с общими границами.
- Если на странице несколько карточек/блоков одного и того же продукта (то же назначение, та же валюта), отличающихся только сроком и/или ставкой (напр. «Кредит 1», «Кредит 2» — варианты одной ипотеки с разным сроком) — это ОДИН продукт, а карточки — его rate_tiers, не отдельные продукты. Разными продуктами считай только реально разные предложения (иное назначение/название/валюта).
- rate_min/rate_max должны равняться минимуму/максимуму rate по rate_tiers.
- name_ru обязателен, если на странице есть русское название; name_tg — таджикское; иначе null.
- Языки СТРОГО не смешивай: name_ru/description_ru — только русский текст, name_tg/description_tg — только таджикский. Если название/описание на странице дано и на русском, и на таджикском — раздели их по соответствующим полям, не склеивай в одно. Никогда не пиши название латиницей/транслитом и не переводи сам — если есть только транслит или английский вариант без кириллицы, оставь name_ru и name_tg null.
- description_ru/description_tg: извлекай ОБЯЗАТЕЛЬНО, если на странице есть текстовое описание, условия, назначение или преимущества продукта (не только таблица цифр) — перескажи их кратко (2-4 предложения) на соответствующем языке. null — только если на странице вообще нет описательного текста.
- key_conditions_ru/key_conditions_tg: если на странице есть блок вроде «Условия продукта»/«Основные условия» с буллетами сверх ставки/суммы/срока (предоплата, комиссия по типу клиента, залог/обеспечение, требования к заёмщику) — вынеси их отдельными пунктами. Не дублируй сюда то, что уже есть в rate_min/rate_max/amount/term — В ТОМ ЧИСЛЕ если разбивка ставки по сроку/сумме на странице оформлена как буллет, а не таблица (см. правило rate_tiers выше): такой буллет идёт ТОЛЬКО в rate_tiers, не сюда. null/[] — если такого блока нет.
- documents_ru/documents_tg: если на странице есть список требуемых документов («Минимальный пакет документов», «Необходимые документы») — вынеси каждый документ отдельным пунктом. null/[] — если не указано.
- НЕ извлекай в products общие блоки «Как получить кредит»/шаги оформления (Заявка → Решение банка → Получение) — это не свойство продукта, а общий процесс банка, одинаковый на всех его страницах.
- features: если про признак ничего не сказано — null (не false).
- subcategory: определи подкатегорию. credit → consumer|mortgage|auto|business|agro|education|refinance|pawn; deposit → term|savings|demand|kids; не подходит/неясно — other; installment → null. Если в начале текста есть строка «Раздел меню: …» — учитывай её как подсказку.
- is_special: true для рефинансирования и реструктуризации долга (в т.ч. если это subcategory=refinance), депозитов/продуктов для легализации денежных средств и прочих нестандартных/аномальных предложений; для обычных продуктов — false.
- Извлекай продукты ТОЛЬКО для физических лиц (частных клиентов). Пропускай продукты, явно обозначенные как «для юридических лиц», «для ИП/индивидуальных предпринимателей», «корпоративным клиентам» и подобные формулировки.
- currency определяй строго по явным признакам на странице: слово «сомони»/«смн»/TJS → TJS; «доллар»/USD/$ → USD; «евро»/EUR/€ → EUR. Не додумывай валюту по умолчанию. Если явных признаков нет — используй TJS (национальная валюта Таджикистана).
- Если на странице рядом с номинальной ставкой указан ПСК/APR/«полная стоимость кредита» (как правило это диапазон шире номинального — учитывает комиссии, страховку, индивидуальный скоринг) — rate_min/rate_max бери ТОЛЬКО из явно подписанной номинальной ставки («Фоиз», «Ставка», «Процентная ставка», «Меъёри фоиз/солона» и т.п.). ПСК/APR/«полная стоимость» — никогда не источник для rate_min/rate_max, даже если номинальная ставка не найдена.
- Не вычисляй ставку сам по примеру расчёта в калькуляторе (сумма кредита/вклада, срок, платёж, переплата, доход) — это иллюстративный пример, не гарантированное условие продукта. Ставку из калькулятора используй, только если на странице ВООБЩЕ нет явно подписанного числа ставки (ни «Фоиз»/«Ставка», ни рядом с продуктом, ни в тарифной сетке) — и в этом случае обязательно опиши в source_note, что ставка вычислена по примеру, а не взята с сайта.`

// systemPrompt — системная инструкция: модель работает как экстрактор,
// обязана вернуть строго JSON по схеме, без выдумывания данных.
// (Анти-галлюцинации: §1, §2 ai-output-schema.md.)
const systemPrompt = `Ты — система извлечения данных о банковских продуктах Таджикистана.
Твоя задача — проанализировать Markdown страницы банка и вернуть СТРОГО JSON по предоставленной схеме.

Жёсткие правила:
- Возвращай ТОЛЬКО JSON-объект вида {"products": [...], "product_links": [...]}. Никакого текста вне JSON.
` + commonExtractionRules + `
- Если на странице нет продуктов нужной категории — верни пустой "products".

Режим каталога (index):
- Если страница — это КАТАЛОГ/меню/список, который лишь ССЫЛАЕТСЯ на отдельные страницы продуктов (а полных условий — ставки/суммы/срока — на самой странице НЕТ), верни "products": [] и заполни "product_links" объектами {"url": "<абсолютная ссылка>", "section": "<заголовок раздела меню или null>"}. Только продукты нужной категории для физлиц, без повторов, без внешних доменов.
- КАЖДЫЙ url в "product_links" ОБЯЗАН дословно встречаться в тексте как markdown-ссылка "[текст](url)". Категорически ЗАПРЕЩЕНО достраивать/придумывать URL по аналогии с другими продуктами той же категории (даже если по смыслу такой продукт «должен» существовать) — если ссылки в тексте нет, продукта в ответе быть не должно. Нарушение этого правила — то же самое, что выдумывание данных.
- Если полные условия продуктов есть прямо на странице — верни "products" и пустой "product_links". Это правило ПРИОРИТЕТНЕЕ наличия ссылок: даже если у карточек/блоков есть свои href на детальные подстраницы (напр. кнопка "Оформить"/"Подробнее"), но условия (ставка/сумма/срок) уже читаются на текущей странице — извлекай "products" отсюда и НЕ уходи в index-режим ради этих ссылок.
- Не клади в "product_links" ссылки на разделы-агрегаторы, рекламу, новости, формы — только конкретные страницы продуктов.`

// userPrompt формирует пользовательское сообщение с категорией-подсказкой,
// URL страницы (см. commonExtractionRules — сигнал, какой из нескольких
// продуктов на странице целевой, если URL — это slug конкретного продукта)
// и Markdown.
func userPrompt(sourceURL, markdown string, category model.Category) string {
	return fmt.Sprintf(
		"Категория продуктов на этой странице: %s.\nURL страницы: %s\nИзвлеки все продукты этой категории.\n\nMarkdown страницы:\n%s",
		category, sourceURL, markdown,
	)
}
